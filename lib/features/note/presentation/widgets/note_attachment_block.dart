enum _ImageViewSize { small, large }

class _ImageTileState extends State<_ImageTile> {
  _ImageViewSize _viewSize = _ImageViewSize.large;
  NoteMediaCursorSide? _cursorSide;

  @override
  Widget build(BuildContext context) {
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        NoteMediaTitle(
          displayName: widget.block.displayName,
          fallbackTitle: 'note_editor_image_fallback_name'.tr,
          fixedTitle: 'note_editor_image_fallback_name'.tr,
          isReadOnly: widget.isReadOnly,
          onChanged: widget.onTitleChanged,
        ),
        Semantics(
          button: true,
          image: true,
          label: '${widget.semanticsLabel}${'note_editor_image_tap_hint'.tr}',
          child: GestureDetector(
            behavior: HitTestBehavior.opaque,
            onTap: _openImagePreview,
            onLongPress: _showContextMenu,
            child: _buildImage(),
          ),
        ),
      ],
    );
  }

  void _openImagePreview() {
    if (_cursorSide != null) setState(() => _cursorSide = null);
    widget.onOpen();
  }

  void _focusImageEdge(NoteMediaCursorSide side) {
    setState(() => _cursorSide = side);
    if (side == NoteMediaCursorSide.before) {
      widget.onFocusBefore();
    } else {
      widget.onFocusAfter();
    }
  }

  void _showContextMenu() {
    if (_cursorSide != null) setState(() => _cursorSide = null);
    Feedback.forLongPress(context);
    showGeneralDialog<void>(
      context: context,
      barrierDismissible: true,
      barrierLabel: MaterialLocalizations.of(context).modalBarrierDismissLabel,
      barrierColor: Colors.transparent,
      transitionDuration: const Duration(milliseconds: 220),
      pageBuilder: (dialogContext, _, _) => _ImageContextMenuOverlay(
        block: widget.block,
        viewSize: _viewSize,
        isReadOnly: widget.isReadOnly,
        onAddImage: widget.onAddImage,
        onCopy: widget.onCopy,
        onPaste: widget.onPaste,
        onCut: widget.onCut,
        onShare: widget.onShare,
        onChooseViewSize: _chooseViewSize,
        onConvertToPdf: widget.onConvertToPdf,
        onDelete: widget.onDelete,
      ),
      transitionBuilder: (_, animation, _, child) {
        final curved = CurvedAnimation(
          parent: animation,
          curve: Curves.easeOutCubic,
          reverseCurve: Curves.easeInCubic,
        );
        return FadeTransition(
          opacity: curved,
          child: ScaleTransition(
            scale: Tween<double>(begin: 0.97, end: 1).animate(curved),
            child: child,
          ),
        );
      },
    );
  }

  Future<void> _chooseViewSize() async {
    final selected = await showCupertinoModalPopup<_ImageViewSize>(
      context: context,
      builder: (sheetContext) => CupertinoActionSheet(
        title: Text('note_editor_view_as'.tr),
        actions: [
          CupertinoActionSheetAction(
            onPressed: () => Navigator.pop(sheetContext, _ImageViewSize.small),
            child: Text('note_editor_view_as_small'.tr),
          ),
          CupertinoActionSheetAction(
            onPressed: () => Navigator.pop(sheetContext, _ImageViewSize.large),
            child: Text('note_editor_view_as_large'.tr),
          ),
        ],
        cancelButton: CupertinoActionSheetAction(
          onPressed: () => Navigator.pop(sheetContext),
          child: Text(MaterialLocalizations.of(context).cancelButtonLabel),
        ),
      ),
    );
    if (!mounted || selected == null) return;
    setState(() => _viewSize = selected);
  }

  Widget _buildImage() {
    final block = widget.block;
    final isSmall = _viewSize == _ImageViewSize.small;
    final imageWidth = isSmall
        ? (widget.width * 0.55).clamp(140.0, 200.0)
        : widget.width;
    final hasFocusedEdge = _cursorSide != null;

    return Align(
      alignment: Alignment.centerLeft,
      child: Container(
        constraints: isSmall
            ? const BoxConstraints(minHeight: 120, maxHeight: 160)
            : const BoxConstraints(),
        width: imageWidth,
        decoration: BoxDecoration(
          border: Border.all(
            color: hasFocusedEdge
                ? AppTheme.folderYellow
                : widget.isDark
                ? Colors.white.withValues(alpha: 0.12)
                : Colors.black.withValues(alpha: 0.08),
            width: hasFocusedEdge ? 1.5 : 1,
          ),
          boxShadow: [
            BoxShadow(
              color: Colors.black.withValues(alpha: widget.isDark ? 0.2 : 0.06),
              blurRadius: 8,
              offset: const Offset(0, 3),
            ),
          ],
        ),
        child: SizedBox(
          width: double.infinity,
          height: isSmall ? 140 : null,
          child: Stack(
            fit: isSmall ? StackFit.expand : StackFit.loose,
            children: [
              ClipRect(
                child: _AttachmentImage(block: block, naturalSize: !isSmall),
              ),
              if (!widget.isReadOnly)
                Positioned.fill(
                  child: NoteMediaCursorEdges(
                    keyPrefix: 'image',
                    focusedSide: _cursorSide,
                    beforeSemanticLabel: 'note_editor_write_before_image'.tr,
                    afterSemanticLabel: 'note_editor_write_after_image'.tr,
                    onFocusBefore: () =>
                        _focusImageEdge(NoteMediaCursorSide.before),
                    onFocusAfter: () =>
                        _focusImageEdge(NoteMediaCursorSide.after),
                  ),
                ),
            ],
          ),
        ),
      ),
    );
  }
}

