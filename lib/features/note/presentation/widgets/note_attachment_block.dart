const _imageExtensions = {
  'jpg',
  'jpeg',
  'png',
  'gif',
  'heic',
  'heif',
  'webp',
  'bmp',
};

const _audioExtensions = {'m4a', 'mp3', 'wav', 'aac', 'caf', 'ogg'};

bool _isAutogeneratedName(String name) {
  final cleanName = name.trim();
  return cleanName.startsWith('image_picker_') ||
      cleanName.startsWith('file_picker_') ||
      cleanName.startsWith('Edited Image') ||
      cleanName == 'Scan.jpg';
}

bool _looksLikeImage(AttachmentBlock block) {
  for (final candidate in [block.displayName, block.localPath, block.url]) {
    final name = candidate?.trim() ?? '';
    if (name.isEmpty || !name.contains('.')) continue;
    if (_imageExtensions.contains(name.split('.').last.toLowerCase())) {
      return true;
    }
  }
  return false;
}

bool _looksLikeAudio(AttachmentBlock block) {
  for (final candidate in [block.displayName, block.localPath, block.url]) {
    final name = candidate?.trim() ?? '';
    if (name.isEmpty || !name.contains('.')) continue;
    if (_audioExtensions.contains(name.split('.').last.toLowerCase())) {
      return true;
    }
  }
  return false;
}

class NoteAttachmentBlock extends StatelessWidget {
  final AttachmentBlock block;
  final int blockIndex;
  final NoteDetailController controller;

  const NoteAttachmentBlock({
    super.key,
    required this.block,
    required this.blockIndex,
    required this.controller,
  });

  @override
  Widget build(BuildContext context) {
    if (looksLikeVideoAttachment(block)) {
      return Padding(
        padding: const EdgeInsets.only(top: 8, bottom: 16),
        child: NoteVideoAttachment(
          key: ValueKey('video-${block.id}'),
          block: block,
          blockIndex: blockIndex,
          controller: controller,
          isReadOnly: controller.isReadOnly.value,
          onDelete: () => controller.deleteBlock(blockIndex),
        ),
      );
    }

    if (_looksLikeAudio(block)) {
      return Padding(
        padding: const EdgeInsets.only(top: 8, bottom: 16),
        child: _AudioTile(
          key: ValueKey('audio-${block.id}'),
          block: block,
          blockIndex: blockIndex,
          isReadOnly: controller.isReadOnly.value,
          controller: controller,
          onDelete: () => controller.deleteBlock(blockIndex),
        ),
      );
    }

    if (!_looksLikeImage(block)) {
      final isPdf = looksLikePdf(block.displayName);
      if (isPdf) {
        return Padding(
          padding: const EdgeInsets.only(top: 8, bottom: 16),
          child: NotePdfAttachment(
            key: ValueKey('scanned-pdf-${block.id}'),
            block: block,
            blockIndex: blockIndex,
            controller: controller,
            isReadOnly: controller.isReadOnly.value,
            onDelete: () => controller.deleteBlock(blockIndex),
          ),
        );
      }
      return Padding(
        padding: const EdgeInsets.only(top: 8, bottom: 16),
        child: _FileTile(
          block: block,
          isReadOnly: controller.isReadOnly.value,
          isPdf: isPdf,
          onTap: () => _openOrShareFile(context),
          onDelete: () => controller.deleteBlock(blockIndex),
          onShare: () => _openOrShareFile(context),
          onCopy: () => unawaited(controller.copyAttachmentBlock(blockIndex)),
          onPaste: () => unawaited(
            controller.pasteClipboardContent(afterIndex: blockIndex),
          ),
          onCut: () => unawaited(controller.cutAttachmentBlock(blockIndex)),

          onEdit: isPdf
              ? () => controller.editPdfSourceImage(blockIndex)
              : null,
          onConvertToImage: isPdf
              ? () => controller.convertPdfToImage(blockIndex)
              : null,
        ),
      );
    }

    final theme = Theme.of(context);
    final isDark = theme.brightness == Brightness.dark;
    final name = block.displayName.trim();

    final semanticsLabel = (name.isEmpty || _isAutogeneratedName(name))
        ? 'note_editor_attachment_semantic_label'.tr
        : 'note_editor_attachment_named_semantic_label'.trParams({
            'name': name,
          });

    return Padding(
      padding: const EdgeInsets.only(top: 8, bottom: 16),

      child: LayoutBuilder(
        builder: (context, constraints) => _ImageTile(
          block: block,
          width: constraints.maxWidth,
          isReadOnly: controller.isReadOnly.value,
          semanticsLabel: semanticsLabel,
          isDark: isDark,
          onOpen: () => _openImagePreview(context),
          onAddImage: () => _addImageOverlay(context),
          onCopy: () => unawaited(_copyImage(context)),
          onPaste: () => unawaited(
            controller.pasteClipboardContent(afterIndex: blockIndex),
          ),
          onCut: () => unawaited(controller.cutAttachmentBlock(blockIndex)),
          onConvertToPdf: () => controller.convertAttachmentToPdf(blockIndex),
          onShare: () => _shareImage(context),
          onDelete: () => controller.deleteBlock(blockIndex),
          onTitleChanged: (title) =>
              controller.updateAttachmentTitle(blockIndex, title),
          onFocusBefore: () =>
              controller.focusTextBesideAttachment(blockIndex, after: false),
          onFocusAfter: () =>
              controller.focusTextBesideAttachment(blockIndex, after: true),
        ),
      ),
    );
  }

  Future<void> _openImageEditor(BuildContext context) async {
    if (controller.isReadOnly.value) return;

    String? pathToEdit = normalizeLocalPath(block.localPath);

    if (pathToEdit == null || !File(pathToEdit).existsSync()) {
      final networkUrl = normalizeAttachmentUrl(block.url);
      if (networkUrl != null && networkUrl.isNotEmpty) {
        await Get.showOverlay(
          asyncFunction: () async {
            pathToEdit = await controller.cacheAttachmentForEditing(networkUrl);
          },
          loadingWidget: const Center(
            child: CupertinoActivityIndicator(radius: 15, color: Colors.white),
          ),
        );
        if (pathToEdit == null) return;
      }
    }

    debugPrint('[IMAGE EDIT] Final Path: $pathToEdit');

    if (pathToEdit == null || !File(pathToEdit!).existsSync()) {
      AppSnackbar.error(
        'note_editor_error_title'.tr,
        'note_editor_image_source_unavailable'.tr,
      );
      return;
    }

    try {
      final String? editedPath = await IOSImageEditor.editImage(pathToEdit!);
      if (editedPath != null && editedPath.isNotEmpty) {
        controller.updateAttachmentImage(blockIndex, editedPath);
      }
    } catch (e) {
      debugPrint('Error opening native editor: $e');
      AppSnackbar.error(
        'note_editor_error_title'.tr,
        'note_editor_could_not_open_image_editor'.tr,
      );
    }
  }

  Future<void> _openImagePreview(BuildContext context) async {
    final path = await _resolveImagePath(context);
    if (path == null || !context.mounted) {
      AppSnackbar.info(
        'note_editor_not_available_title'.tr,
        'note_editor_image_not_on_device'.tr,
      );
      return;
    }

    await Navigator.of(context).push(
      CupertinoPageRoute<void>(
        fullscreenDialog: true,
        builder: (_) => _ImagePreviewPage(
          path: path,
          title: 'note_editor_image_fallback_name'.tr,
          onEdit: controller.isReadOnly.value
              ? null
              : () => _openImageEditor(context),
          onShare: () => _shareImage(context),
        ),
      ),
    );
  }

  Future<void> _addImageOverlay(BuildContext context) async {
    if (controller.isReadOnly.value) return;

    final basePath = await _resolveImagePath(context);
    if (basePath == null) {
      AppSnackbar.info(
        'note_editor_not_available_title'.tr,
        'note_editor_image_not_on_device'.tr,
      );
      return;
    }

    final pickedImage = await ImagePicker().pickImage(
      source: ImageSource.gallery,
    );
    if (pickedImage == null || !context.mounted) return;

    final composedPath = await Navigator.of(context).push<String>(
      CupertinoPageRoute(
        fullscreenDialog: true,
        builder: (_) => ImageOverlayComposerPage(
          baseImagePath: basePath,
          overlayImagePath: pickedImage.path,
        ),
      ),
    );
    if (composedPath == null || composedPath.isEmpty) return;

    try {
      final editedPath = await IOSImageEditor.editImage(composedPath);
      if (editedPath != null && editedPath.isNotEmpty) {
        controller.updateAttachmentImage(blockIndex, editedPath);
      }
    } catch (error) {
      debugPrint('[IMAGE OVERLAY EDIT ERROR] $error');
      AppSnackbar.error(
        'note_editor_error_title'.tr,
        'note_editor_could_not_open_image_editor'.tr,
      );
    }
  }

  Future<void> _shareImage(BuildContext context) async {
    final path = await _resolveImagePath(context);
    if (path == null) {
      AppSnackbar.info(
        'note_editor_not_available_title'.tr,
        'note_editor_image_not_on_device'.tr,
      );
      return;
    }
    if (!context.mounted) return;
    try {
      await shareXFilesSafely(context, [XFile(path)]);
    } catch (e) {
      debugPrint('[IMAGE SHARE ERROR] $e');
      AppSnackbar.error(
        'note_editor_error_title'.tr,
        'note_editor_could_not_share_image'.tr,
      );
    }
  }

  Future<void> _copyImage(BuildContext context) async {
    final path = await _resolveImagePath(context);
    if (path == null) {
      AppSnackbar.info(
        'note_editor_not_available_title'.tr,
        'note_editor_image_not_on_device'.tr,
      );
      return;
    }

    final stagedInApp = await controller.copyAttachmentBlock(
      blockIndex,
      showFeedback: false,
    );
    var copiedToDevice = false;
    try {
      final bridge = QuillNativeBridge();
      final supported = await bridge.isSupported(
        QuillNativeBridgeFeature.copyImageToClipboard,
      );
      if (supported) {
        await bridge.copyImageToClipboard(await File(path).readAsBytes());
        copiedToDevice = true;
      }
    } catch (error) {
      debugPrint('[SYSTEM IMAGE COPY ERROR] $error');
    }

    if (stagedInApp || copiedToDevice) {
      AppSnackbar.success('note_editor_image_copied'.tr);
    } else {
      AppSnackbar.error(
        'note_editor_error_title'.tr,
        'note_editor_could_not_copy_image'.tr,
      );
    }
  }

  Future<String?> _resolveImagePath(BuildContext context) async {
    final localPath = normalizeLocalPath(block.localPath);
    if (localPath != null && File(localPath).existsSync()) return localPath;

    final networkUrl = normalizeAttachmentUrl(block.url);
    if (networkUrl == null || networkUrl.isEmpty) return null;

    String? cachedPath;
    await Get.showOverlay(
      asyncFunction: () async {
        cachedPath = await controller.cacheAttachmentForEditing(networkUrl);
      },
      loadingWidget: const Center(
        child: CupertinoActivityIndicator(radius: 15, color: Colors.white),
      ),
    );
    if (!context.mounted || cachedPath == null) return null;
    return File(cachedPath!).existsSync() ? cachedPath : null;
  }

  Future<void> _openOrShareFile(BuildContext context) async {
    final path = normalizeLocalPath(block.localPath);
    if (path == null || !File(path).existsSync()) {
      AppSnackbar.info(
        'note_editor_not_available_title'.tr,
        'note_editor_file_not_on_device'.tr,
      );
      return;
    }
    try {
      await shareXFilesSafely(context, [XFile(path)]);
    } catch (e) {
      debugPrint('[FILE SHARE ERROR] $e');
      AppSnackbar.error(
        'note_editor_error_title'.tr,
        'note_editor_could_not_open_file'.tr,
      );
    }
  }
}

